/** "INGLATERRA: Premier League" → "ENGLAND: Premier League". Lo que ya está en inglés no cambia. */
export function canonicalCompetition(competition: string): string {
  const cut = competition.indexOf(":");
  if (cut <= 0) return competition;
  const prefix = competition.slice(0, cut).trim().toUpperCase();
  const english = ES_TO_EN[prefix];
  return english ? `${english}${competition.slice(cut)}` : competition;
}
